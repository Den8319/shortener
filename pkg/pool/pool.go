// Package pool предоставляет-generic пул объектов с автоматическим сбросом состояния.
//
// Пул использует sync.Pool для повторного использования «тяжёлых» объектов.
// При возвращении объекта в пул вызывается его метод Reset(), гарантируя,
// что следующий получатель всегда получает «чистый» объект.
//
// Тип объектов ограничен интерфейсом Resetter — любой тип, реализующий
// метод Reset(), включая структуры, для которых метод сгенерирован
// утилитой cmd/reset.
package pool

import "sync"

// Resetter — ограничение типа для объектов, поддерживающих сброс состояния.
type Resetter interface {
	Reset()
}

// Pool — потокобезопасный пул объектов типа T, реализующих Resetter.
// Использует sync.Pool под капотом для эффективного переиспользования.
type Pool[T Resetter] struct {
	inner sync.Pool
}

// New создаёт новый пул объектов. Функция newFn вызывается при нехватке
// свободных объектов в пуле — она должна возвращать новый экземпляр T.
func New[T Resetter](newFn func() T) *Pool[T] {
	return &Pool[T]{
		inner: sync.Pool{
			New: func() any {
				return newFn()
			},
		},
	}
}

// Get возвращает объект из пула. Если пул пуст — создаёт новый через newFn.
func (p *Pool[T]) Get() T {
	return p.inner.Get().(T)
}

// Put возвращает объект в пул, предварительно сбросив его состояние
// вызовом Reset(). Объект после вызова Put больше не должен использоваться.
func (p *Pool[T]) Put(v T) {
	v.Reset()
	p.inner.Put(v)
}
