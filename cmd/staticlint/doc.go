// Package staticlint содержит документацию для multichecker.
//
// # Multichecker
//
// Multichecker — это инструмент статического анализа, объединяющий несколько
// анализаторов в одном бинарнике. Он включает стандартные анализаторы из
// golang.org/x/tools/go/analysis/passes, анализаторы staticcheck (классы SA, ST, QF),
// сторонние публичные анализаторы и собственный анализатор noexit.
//
// # Сборка и запуск
//
// Сборка бинарника:
//
//	go build -o staticlint ./cmd/staticlint
//
// Запуск анализа всего проекта:
//
//	./staticlint ./...
//
// Запуск анализа конкретного пакета:
//
//	./staticlint ./internal/handler/...
//
// # Состав анализаторов
//
// ## 1. Стандартные анализаторы (golang.org/x/tools/go/analysis/passes)
//
// Эти анализаторы входят в состав модуля golang.org/x/tools и проверяют
// типичные ошибки Go-кода:
//
//   - appends — проверяет аргументы функции append на корректность.
//   - asmdecl — проверяет соответствие между Go-декларациями и ассемблерным кодом.
//   - assign — проверяет ошибки присваивания (например, бесполезные присваивания).
//   - atomic — проверяет корректность использования пакета sync/atomic.
//   - atomicalign — проверяет выравнивание 64-битных атомарных операций.
//   - bools — проверяет логические ошибки в условиях (например, x || !x).
//   - buildtag — проверяет корректность build-тегов.
//   - composite — проверяет корректность композитных литералов.
//   - copylock — проверяет копирование значений, содержащих мьютексы.
//   - deepequalerrors — проверяет использование reflect.DeepEqual для ошибок.
//   - defers — проверяет ошибки в defer-вызовах (например, циклические ссылки).
//   - directive — проверяет корректность прагма-директив (//go: и //lint:).
//   - errorsas — проверяет аргументы функции errors.As.
//   - framepointer — проверяет корректность использования указателей кадра.
//   - httpresponse — проверяет, что ответ HTTP-сервера записывается перед вызовом WriteHeader.
//   - ifaceassert — проверяет невозможные утверждения типа для интерфейсов.
//   - loopclosure — проверяет захват переменных цикла в замыканиях.
//   - lostcancel — проверяет потерю контекста отмены (context.CancelFunc).
//   - nilfunc — проверяет сравнение функций с nil.
//   - nilness — проверяет потенциальные обращения к nil-указателям.
//   - printf — проверяет форматы строковых функций (Printf, Sprintf и т.д.).
//   - reflectvaluecompare — проверяет некорректное сравнение reflect.Value.
//   - shadow — проверяет затенение переменных.
//   - shift — проверяет корректность операций сдвига.
//   - sigchanyzer — проверяет некорректное использование signal.Notify с nil-каналом.
//   - slog — проверяет корректность использования пакета log/slog.
//   - sortslice — проверяет корректность sort.Slice с несортируемыми типами.
//   - stdmethods — проверяет сигнатуры стандартных методов (MarshalJSON, String и т.д.).
//   - stdversion — проверяет использование функций, устаревших в текущей версии Go.
//   - stringintconv — проверяет конвертацию int в string ( rune(x) вместо string(x)).
//   - structtag — проверяет корректность тегов структур.
//   - testinggoroutine — проверяет использование testing API в горутинах.
//   - tests — проверяет корректность тестовых функций.
//   - timeformat — проверяет форматы времени (например, 2006-01-02 вместо 2023-01-02).
//   - unmarshal — проверяет корректность передачи указателей в Unmarshal-функции.
//   - unreachable — проверяет недостижимый код.
//   - unsafeptr — проверяет некорректное использование unsafe.Pointer.
//   - unusedresult — проверяет неиспользуемые результаты вызовов функций.
//   - unusedwrite — проверяет неиспользуемые записи в структуры.
//   - waitgroup — проверяет корректность использования sync.WaitGroup.
//
// ## 2. Анализаторы класса SA (Static Analysis) из staticcheck
//
// Класс SA содержит анализаторы, находящие баги и проблемы производительности.
// Код, помеченный этими анализаторами, как правило, требует исправления.
// Полный список: SA1000–SA9000 (более 80 анализаторов).
// Примеры: SA1019 (deprecated), SA4006 (unused value), SA9003 (empty branch).
//
// ## 3. Анализаторы класса ST (Style) из stylecheck
//
// Класс ST содержит анализаторы стиля кода. Они проверяют соответствие
// общепринятым конвенциям Go-сообщества.
// Примеры: ST1000 (комментарий к пакету), ST1003 (именование), ST1019 (импорт).
//
// ## 4. Анализаторы класса QF (Quickfix) из quickfix
//
// Класс QF содержит анализаторы, предлагающие быстрые исправления (рефакторинги).
// Они не обязательны к исправлению, но улучшают читаемость кода.
// Примеры: QF1001 (unwrap if), QF1003 (convert if-else to switch).
//
// ## 5. Сторонние публичные анализаторы
//
//   - nilerr (github.com/gostaticanalysis/nilerr) — проверяет, не возвращается ли
//     nil, когда err != nil. Помогает находить пропущенные проверки ошибок.
//   - bodyclose (github.com/timakin/bodyclose) — проверяет, что тело HTTP-ответа
//     (http.Response.Body) обязательно закрывается. Незакрытое тело приводит к
//     утечке соединений и goroutine.
//
// ## 6. Собственный анализатор noexit
//
//   - noexit (cmd/staticlint/noexit) — запрещает прямой вызов os.Exit в функции
//     main пакета main. Прямой вызов os.Exit обходит defer-вызовы, что может
//     привести к утечке ресурсов (незакрытые файлы, соединения с БД и т.д.).
//     Вместо os.Exit следует использовать log.Fatal или возвращать ошибку из main.
